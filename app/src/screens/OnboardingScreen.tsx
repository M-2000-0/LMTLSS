/* Onboarding — the first half of the M1 slice.

   Collects only what the domain actually needs to generate a plan
   (goal, sports, experience, days/week, equipment) and hands the profile to
   the store, which calls Domain.planFor(). Nothing here invents a plan. */

import { useState } from 'react';
import {
  KeyboardAvoidingView,
  Platform,
  Pressable,
  ScrollView,
  StyleSheet,
  Text,
  TextInput,
  View,
} from 'react-native';
import { SafeAreaView } from 'react-native-safe-area-context';

import { EXPERIENCE_LABELS, GOAL_LABELS } from '../domain';
import type { Experience, Goal } from '../../../shared/src/types';
import { Chip, Logo, PrimaryButton, SectionLabel, preloadLogo } from '../components/ui';
import { appStore } from '../store/appStore';
import { colors, radius, space, type as typeScale } from '../theme';

const GOALS: Goal[] = ['strength', 'hypertrophy', 'general', 'endurance', 'weight'];
const EXPERIENCES: Experience[] = ['beginner', 'intermediate', 'advanced'];
const SPORTS = [
  { id: 'strength', label: 'Strength training' },
  { id: 'running', label: 'Running' },
  { id: 'cycling', label: 'Cycling' },
  { id: 'swimming', label: 'Swimming' },
  { id: 'walking', label: 'Walking' },
  { id: 'hiking', label: 'Hiking' },
  { id: 'calisthenics', label: 'Calisthenics' },
  { id: 'hiit', label: 'HIIT / Circuit' },
  { id: 'yoga', label: 'Yoga' },
  { id: 'boxing', label: 'Boxing' },
  { id: 'martial-arts', label: 'Martial Arts' },
];
const EQUIPMENT = [
  { id: 'full-gym', label: 'Full gym' },
  { id: 'dumbbells', label: 'Dumbbells' },
  { id: 'bar', label: 'Pull-up bar' },
  { id: 'bodyweight', label: 'Bodyweight only' },
];

const STEPS = ['You', 'Your week', 'Equipment'] as const;

export default function OnboardingScreen() {
  const [step, setStep] = useState(0);
  const [name, setName] = useState('');
  const [goal, setGoal] = useState<Goal>('general');
  const [sports, setSports] = useState<string[]>(['strength']);
  const [experience, setExperience] = useState<Experience>('beginner');
  const [daysPerWeek, setDaysPerWeek] = useState(3);
  const [equipment, setEquipment] = useState<string[]>(['full-gym']);

  function toggleSport(id: string) {
    setSports((current) =>
      current.includes(id)
        ? current.length > 1
          ? current.filter((s) => s !== id)
          : current // never leave the athlete with zero sports
        : [...current, id],
    );
  }

  function toggleEquipment(id: string) {
    setEquipment((current) => {
      if (id === 'full-gym') return ['full-gym'];
      const withoutGym = current.filter((e) => e !== 'full-gym');
      if (withoutGym.includes(id)) {
        const next = withoutGym.filter((e) => e !== id);
        return next.length ? next : ['bodyweight'];
      }
      return [...withoutGym, id];
    });
  }

    preloadLogo();

  function finish() {
    appStore.completeOnboarding({
      name,
      goal,
      sports,
      experience,
      daysPerWeek,
      equipment,
    });
  }

  const last = step === STEPS.length - 1;

  return (
    <SafeAreaView style={styles.safe} edges={['top', 'bottom']}>
      <KeyboardAvoidingView
        style={styles.flex}
        behavior={Platform.OS === 'ios' ? 'padding' : undefined}
      >
        <ScrollView
          contentContainerStyle={styles.content}
          keyboardShouldPersistTaps="handled"
          showsVerticalScrollIndicator={false}        >
        <View style={styles.brandRow}>
            <Logo size={48} />
            <View style={styles.brandText}>
              <Text style={styles.brand}>LMTLSS</Text>
              <Text style={styles.tagline}>TRAINING LOG</Text>
            </View>
            <Text style={styles.stepCount}>
              {step + 1} / {STEPS.length}
            </Text>
          </View>

          {step === 0 ? (
            <View style={styles.block}>
              <Text style={styles.h1}>Let&apos;s build your week.</Text>
              <Text style={styles.lede}>
                A few answers and you get a real training week — generated by the same engine the
                reference app uses, then adjusted as you train.
              </Text>

              <View style={styles.field}>
                <SectionLabel>Name (optional)</SectionLabel>
                <TextInput
                  value={name}
                  onChangeText={setName}
                  placeholder="What should we call you?"
                  placeholderTextColor={colors.textMuted}
                  style={styles.input}
                  autoCapitalize="words"
                  returnKeyType="done"
                  accessibilityLabel="Your name"
                />
              </View>

              <View style={styles.field}>
                <SectionLabel>What are you training for?</SectionLabel>
                <View style={styles.chips}>
                  {GOALS.map((id) => (
                    <Chip
                      key={id}
                      label={GOAL_LABELS[id] ?? id}
                      selected={goal === id}
                      onPress={() => setGoal(id)}
                    />
                  ))}
                </View>
              </View>
            </View>
          ) : null}

          {step === 1 ? (
            <View style={styles.block}>
              <Text style={styles.h1}>How does your week look?</Text>
              <Text style={styles.lede}>
                Days per week sets how the plan spaces sessions. Select one or more sports you want
                to focus on.
              </Text>

              <View style={styles.field}>
                <SectionLabel>Days per week</SectionLabel>
                <View style={styles.stepper}>
                  <Pressable
                    accessibilityRole="button"
                    accessibilityLabel="Fewer days"
                    onPress={() => setDaysPerWeek((d) => Math.max(2, d - 1))}
                    style={({ pressed }) => [styles.stepperButton, pressed && styles.pressed]}
                  >
                    <Text style={styles.stepperLabel}>−</Text>
                  </Pressable>
                  <View style={styles.stepperValueWrap}>
                    <Text style={styles.stepperValue}>{daysPerWeek}</Text>
                    <Text style={styles.stepperHint}>days</Text>
                  </View>
                  <Pressable
                    accessibilityRole="button"
                    accessibilityLabel="More days"
                    onPress={() => setDaysPerWeek((d) => Math.min(6, d + 1))}
                    style={({ pressed }) => [styles.stepperButton, pressed && styles.pressed]}
                  >
                    <Text style={styles.stepperLabel}>+</Text>
                  </Pressable>
                </View>
              </View>

              <View style={styles.field}>
                <SectionLabel>Sports</SectionLabel>
                <View style={styles.chips}>
                  {SPORTS.map((sport) => (
                    <Chip
                      key={sport.id}
                      label={sport.label}
                      selected={sports.includes(sport.id)}
                      onPress={() => toggleSport(sport.id)}
                    />
                  ))}
                </View>
              </View>

              <View style={styles.field}>
                <SectionLabel>Experience</SectionLabel>
                <View style={styles.chips}>
                  {EXPERIENCES.map((id) => (
                    <Chip
                      key={id}
                      label={EXPERIENCE_LABELS[id] ?? id}
                      selected={experience === id}
                      onPress={() => setExperience(id)}
                    />
                  ))}
                </View>
              </View>
            </View>
          ) : null}

          {step === 2 ? (
            <View style={styles.block}>
              <Text style={styles.h1}>What do you train with?</Text>
              <Text style={styles.lede}>
                Sessions only suggest exercises you can actually do. Full gym means everything;
                otherwise the plan adapts to what you pick.
              </Text>
              <View style={styles.field}>
                <SectionLabel>Equipment</SectionLabel>
                <View style={styles.chips}>
                  {EQUIPMENT.map((item) => (
                    <Chip
                      key={item.id}
                      label={item.label}
                      selected={equipment.includes(item.id)}
                      onPress={() => toggleEquipment(item.id)}
                    />
                  ))}
                </View>
              </View>
              <Text style={styles.footnote}>
                Your data stays on this device. No account, no sync, no tracking.
              </Text>
            </View>
          ) : null}

          <View style={styles.actions}>
            <PrimaryButton
              label={last ? 'Build my plan' : 'Continue'}
              onPress={() => {
                if (last) finish();
                else setStep((s) => s + 1);
              }}
            />
            {step > 0 ? (
              <Pressable
                accessibilityRole="button"
                onPress={() => setStep((s) => s - 1)}
                style={({ pressed }) => [styles.back, pressed && styles.pressed]}
              >
                <Text style={styles.backLabel}>Back</Text>
              </Pressable>
            ) : null}
          </View>
        </ScrollView>
      </KeyboardAvoidingView>
    </SafeAreaView>
  );
}

const styles = StyleSheet.create({
  safe: { backgroundColor: colors.bg, flex: 1 },
  flex: { flex: 1 },
  content: {
    gap: space.s6,
    paddingBottom: space.s8,
    paddingHorizontal: space.s5,
    paddingTop: space.s4,
  },
  brandRow: {
    alignItems: 'center',
    flexDirection: 'row',
    justifyContent: 'space-between',
  },
  brandText: {
    alignItems: 'flex-start',
    flexDirection: 'column',
  },
  brand: { ...typeScale.micro, color: colors.text, letterSpacing: 3 },
  tagline: { ...typeScale.small, color: colors.textMuted, letterSpacing: 1.5 },
  stepCount: { ...typeScale.small, color: colors.textMuted },
  block: { gap: space.s5 },
  h1: { ...typeScale.title, color: colors.text, lineHeight: 28 },
  lede: { ...typeScale.small, color: colors.textSecondary, lineHeight: 20 },
  field: { gap: space.s3 },
  chips: { flexDirection: 'row', flexWrap: 'wrap', gap: space.s2 },
  input: {
    backgroundColor: colors.surface,
    borderColor: colors.border,
    borderRadius: radius.md,
    borderWidth: 1,
    color: colors.text,
    fontSize: 16,
    paddingHorizontal: space.s4,
    paddingVertical: space.s3 + 2,
  },
  stepper: {
    alignItems: 'center',
    flexDirection: 'row',
    justifyContent: 'space-between',
  },
  stepperButton: {
    alignItems: 'center',
    borderColor: colors.border,
    borderRadius: radius.md,
    borderWidth: 1,
    height: 52,
    justifyContent: 'center',
    width: 64,
  },
  stepperLabel: { color: colors.text, fontSize: 24, fontWeight: '600' },
  stepperValueWrap: { alignItems: 'center' },
  stepperValue: { ...typeScale.metric, color: colors.accent },
  stepperHint: { ...typeScale.small, color: colors.textMuted },
  footnote: { ...typeScale.small, color: colors.textMuted, lineHeight: 18 },
  actions: { gap: space.s3, marginTop: space.s2 },
  back: { alignItems: 'center', paddingVertical: space.s2 },
  backLabel: { ...typeScale.small, color: colors.textSecondary, fontWeight: '600' },
  pressed: { opacity: 0.6 },
});
