/* The app store: owns the in-memory AppState, persists it, and binds it into
   the shared domain.

   Why a factory: the store's two dependencies (storage, clock) are injected, so
   tests drive a real store over an in-memory adapter with a fixed calendar day
   instead of mocking modules. The app uses the singleton below.

   Contract with the domain: shared/ never reads storage. It asks for state via
   getPlatformBindings().getState(), which this store points at its live state
   object after hydration. That is the whole wiring seam. */

import { useEffect, useSyncExternalStore } from 'react';

import type {
  AppState,
  Experience,
  Goal,
  Profile,
  ReadinessEntry,
} from '../../../shared/src/types';
import { planFor, setPlatformBindings, todayISO } from '../domain';
import { emptyState } from './schema';
import { asyncStorageAdapter, type LoadResult, type StoreStorage } from './storage';

export interface StoreSnapshot {
  /** False until the first read from disk has settled. */
  ready: boolean;
  state: AppState;
  /** Stored bytes existed but could not be read (reason). Original is preserved. */
  quarantine: string | null;
  /** Storage or a write failed; the UI must show this, never hide it. */
  storageError: string | null;
}

export interface OnboardingInput {
  name?: string;
  goal: Goal;
  sports: string[];
  experience: Experience;
  daysPerWeek: number;
  equipment: string[];
  limitations?: string;
}

export interface ReadinessInput {
  energy: number;
  soreness?: number;
  note?: string;
}

export interface AppStore {
  getSnapshot(): StoreSnapshot;
  subscribe(listener: () => void): () => void;
  hydrate(): Promise<StoreSnapshot>;
  /** Resolves once every queued write has settled (tests, backgrounding). */
  whenIdle(): Promise<void>;
  completeOnboarding(input: OnboardingInput): void;
  logReadiness(input: ReadinessInput): void;
  addHydration(ml: number): void;
}

export function createAppStore(storage: StoreStorage, clock: () => string = todayISO): AppStore {
  let snapshot: StoreSnapshot = {
    ready: false,
    state: emptyState(),
    quarantine: null,
    storageError: null,
  };
  const listeners = new Set<() => void>();
  let hydration: Promise<StoreSnapshot> | null = null;
  let writes: Promise<void> = Promise.resolve();

  function emit(): void {
    listeners.forEach((listener) => listener());
  }

  function patch(next: Partial<StoreSnapshot>): void {
    snapshot = { ...snapshot, ...next };
    emit();
  }

  /* Writes are serialised so an older snapshot can never land after a newer
     one. A failure keeps the change in memory and surfaces the message. */
  function flush(): void {
    const target = snapshot.state;
    writes = writes
      .then(async () => {
        const result = await storage.write(target);
        if (target !== snapshot.state) return; // a newer write speaks for current state
        patch({ storageError: result.ok ? null : (result.message ?? "Couldn't save to this device.") });
      })
      .catch(() => {
        patch({ storageError: "Couldn't save to this device." });
      });
  }

  function update(mutate: (state: AppState) => AppState): void {
    snapshot = { ...snapshot, state: mutate(snapshot.state) };
    emit();
    flush();
  }

  function hydrate(): Promise<StoreSnapshot> {
    if (hydration) return hydration;
    hydration = (async () => {
      let result: LoadResult;
      try {
        result = await storage.read();
      } catch {
        // Unreachable through the AsyncStorage adapter, but a custom adapter
        // must not be able to wedge the app on the boot screen.
        result = { state: emptyState(), storageError: 'Local storage is unavailable on this device.' };
      }
      snapshot = {
        ready: true,
        state: result.state,
        quarantine: result.quarantine ?? null,
        storageError: result.storageError ?? null,
      };
      setPlatformBindings({ getState: () => snapshot.state, todayISO: clock });
      emit();
      return snapshot;
    })();
    return hydration;
  }

  function completeOnboarding(input: OnboardingInput): void {
    const profile: Profile = {
      goal: input.goal,
      sports: input.sports.slice(),
      experience: input.experience,
      daysPerWeek: input.daysPerWeek,
      equipment: input.equipment.slice(),
      seeded: false,
    };
    if (input.name && input.name.trim()) profile.name = input.name.trim();
    if (input.limitations && input.limitations.trim()) profile.limitations = input.limitations.trim();

    // The plan is generated by the shared domain, never by a screen.
    const plan = planFor(profile);
    update((state) => ({ ...state, profile, plan }));
  }

  function logReadiness(input: ReadinessInput): void {
    const date = clock();
    const entry: ReadinessEntry = { date, energy: input.energy };
    if (typeof input.soreness === 'number') entry.soreness = input.soreness;
    if (input.note && input.note.trim()) entry.note = input.note.trim();

    update((state) => {
      const rows = (state.readiness ?? []).slice();
      const at = rows.findIndex((row) => row.date === date);
      if (at >= 0) rows[at] = entry;
      else rows.push(entry);
      return { ...state, readiness: rows };
    });
  }

  function addHydration(ml: number): void {
    if (!Number.isFinite(ml) || ml <= 0) return;
    const date = clock();
    update((state) => {
      const rows = (state.hydration ?? []).map((row) => ({ ...row }));
      const row = rows.find((r) => r.date === date);
      if (row) row.ml += ml;
      else rows.push({ date, ml });
      return { ...state, hydration: rows };
    });
  }

  return {
    getSnapshot: () => snapshot,
    subscribe(listener) {
      listeners.add(listener);
      return () => {
        listeners.delete(listener);
      };
    },
    hydrate,
    whenIdle: () => writes,
    completeOnboarding,
    logReadiness,
    addHydration,
  };
}

/** The app's store. Screens read it through useAppStore(). */
export const appStore = createAppStore(asyncStorageAdapter());

export function useAppStore(): StoreSnapshot {
  const snapshot = useSyncExternalStore(
    appStore.subscribe,
    appStore.getSnapshot,
    appStore.getSnapshot,
  );
  useEffect(() => {
    void appStore.hydrate();
  }, []);
  return snapshot;
}
